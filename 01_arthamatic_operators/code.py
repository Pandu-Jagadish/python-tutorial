# Arthematic Operators in Python

x = 10
y = 3

# Addition
addition = x + y
print("Addition:", addition)  # Output: 13      

#subtraction
subtraction = x - y
print("Subtraction:", subtraction)  # Output: 7

# Multiplication
multiplication = x * y
print("Multiplication:", multiplication)  # Output: 30

# Division
division = x / y
print("Division:", division)  # Output:     

# Floor Division
floor_division = x // y
print("Floor Division:", floor_division)  # Output: 3

# Modulus
modulus = x % y
print("Modulus:", modulus)  # Output: 1

# Exponentiation
exponentiation = x ** y
print("Exponentiation:", exponentiation)  # Output: 1000